package de.planmarshall.api.designer;

import java.io.IOException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

import de.planmarshall.api.json.JsonFormatException;
import de.planmarshall.api.json.JsonTree;

/**
 * One building block of the runtime's catalogue (UC-PLN-3).
 * <p>
 * The catalogue is generated by the runtime from the registries its validation uses; the client
 * keeps no list of its own, so a block it offers is one validation accepts.
 *
 * @param kind         the closed category of the block
 * @param name         the block's name as written in a unit (e.g. {@code git.commit_and_push})
 * @param summary      a one-line summary ({@code designer.blocks.detail})
 * @param template     the text the block inserts at the cursor
 * @param parameters   the parameters the block takes (name and type, e.g. {@code message_mode enum})
 * @param constraints  what the block needs (a role, a skill, a configuration key)
 * @param outcomes     the block's outcomes with their classes (e.g. {@code done (success)})
 * @param usedIn       where the block may be used (the clauses and unit kinds that take it)
 * @param compiledOnly whether this is a compiled-only unit: called, never replaced
 */
public record BuildingBlock(
        BlockKind kind,
        String name,
        String summary,
        String template,
        List<String> parameters,
        List<String> constraints,
        List<String> outcomes,
        List<String> usedIn,
        boolean compiledOnly
) {
    private static final String FIELD_KIND = "kind";
    private static final String FIELD_NAME = "name";
    private static final String FIELD_SUMMARY = "summary";
    private static final String FIELD_TEMPLATE = "template";
    private static final String FIELD_PARAMETERS = "parameters";
    private static final String FIELD_CONSTRAINTS = "constraints";
    private static final String FIELD_OUTCOMES = "outcomes";
    private static final String FIELD_USED_IN = "used_in";
    private static final String FIELD_COMPILED_ONLY = "compiled_only";

    /**
     * Compact constructor validating required properties.
     */
    public BuildingBlock {
        Objects.requireNonNull(kind, FIELD_KIND);
        Objects.requireNonNull(name, FIELD_NAME);
        summary = summary != null ? summary : "";
        template = template != null ? template : "";
        parameters = parameters != null ? List.copyOf(parameters) : List.of();
        constraints = constraints != null ? List.copyOf(constraints) : List.of();
        outcomes = outcomes != null ? List.copyOf(outcomes) : List.of();
        usedIn = usedIn != null ? List.copyOf(usedIn) : List.of();
    }

    /**
     * @return this block as a JSON tree
     */
    public Map<String, Object> toMap() {
        var map = new LinkedHashMap<String, Object>();
        map.put(FIELD_KIND, kind.wire());
        map.put(FIELD_NAME, name);
        map.put(FIELD_SUMMARY, summary);
        map.put(FIELD_TEMPLATE, template);
        map.put(FIELD_PARAMETERS, parameters);
        map.put(FIELD_CONSTRAINTS, constraints);
        map.put(FIELD_OUTCOMES, outcomes);
        map.put(FIELD_USED_IN, usedIn);
        map.put(FIELD_COMPILED_ONLY, compiledOnly);
        return map;
    }

    /**
     * @return this block as compact JSON
     */
    public String toJson() {
        return JsonTree.write(toMap());
    }

    /**
     * Parses a block from a JSON tree.
     *
     * @param map the input tree
     * @return the block
     * @throws IOException on a malformed tree
     */
    public static BuildingBlock fromMap(Map<String, Object> map) throws IOException {
        Objects.requireNonNull(map, "map");
        var kind = BlockKind.fromWire(JsonTree.string(map, FIELD_KIND));
        var name = JsonTree.string(map, FIELD_NAME);
        if (kind == null || name == null) {
            throw new JsonFormatException("BuildingBlock requires a known kind and a name");
        }
        return new BuildingBlock(
                kind,
                name,
                JsonTree.string(map, FIELD_SUMMARY),
                JsonTree.string(map, FIELD_TEMPLATE),
                DesignerJson.stringList(map, FIELD_PARAMETERS),
                DesignerJson.stringList(map, FIELD_CONSTRAINTS),
                DesignerJson.stringList(map, FIELD_OUTCOMES),
                DesignerJson.stringList(map, FIELD_USED_IN),
                Boolean.TRUE.equals(map.get(FIELD_COMPILED_ONLY))
        );
    }

    /**
     * Parses a block from JSON.
     *
     * @param json the JSON text
     * @return the block
     * @throws IOException on a malformed document
     */
    public static BuildingBlock fromJson(String json) throws IOException {
        var obj = JsonTree.asObject(JsonTree.parse(json));
        if (obj == null) {
            throw new JsonFormatException("Expected a JSON object for BuildingBlock");
        }
        return fromMap(obj);
    }

    /**
     * Parses a list of blocks from a JSON array string.
     *
     * @param json the JSON text
     * @return the blocks
     * @throws IOException on a malformed document
     */
    public static List<BuildingBlock> parseList(String json) throws IOException {
        var parsed = JsonTree.parse(json);
        if (!(parsed instanceof List<?> list)) {
            throw new JsonFormatException("Expected a JSON array for a BuildingBlock list");
        }
        var result = new ArrayList<BuildingBlock>(list.size());
        for (var item : list) {
            var map = JsonTree.asObject(item);
            if (map != null) {
                result.add(fromMap(map));
            }
        }
        return result;
    }

    /**
     * Serializes a list of blocks to a JSON array string.
     *
     * @param blocks the blocks
     * @return the JSON text
     */
    public static String writeList(List<BuildingBlock> blocks) {
        return JsonTree.write(blocks.stream().map(BuildingBlock::toMap).toList());
    }
}
